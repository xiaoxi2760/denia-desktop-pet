const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('pet', {
  hitRect: (rect) => ipcRenderer.send('pet:hit-rect', rect),
  setInteractive: (v) => ipcRenderer.send('pet:set-interactive', v),
  setWindowOffset: (dy) => ipcRenderer.send('pet:window-offset', dy),
  getScreen: () => ipcRenderer.invoke('pet:get-screen'),
  env: () => ipcRenderer.invoke('pet:env'),
  walkTo: (x, y, durationMs) => ipcRenderer.send('pet:walk-to', { x, y, durationMs }),
  walkStop: () => ipcRenderer.send('pet:walk-stop'),
  contextMenu: () => ipcRenderer.send('pet:context-menu'),
  dragStart: () => ipcRenderer.send('pet:drag-start'),
  dragEnd: () => ipcRenderer.send('pet:drag-end'),
  quit: () => ipcRenderer.send('pet:quit'),
  info: () => ipcRenderer.invoke('pet:info'),
  idleTime: () => ipcRenderer.invoke('pet:idle'),
  say: (text) => ipcRenderer.invoke('pet:say', text),
  voice: (text) => ipcRenderer.invoke('pet:voice', text),
  asr: (wav) => ipcRenderer.invoke('pet:asr', wav),
  scale: (f) => ipcRenderer.send('pet:scale', f),
  peek: () => ipcRenderer.send('pet:peek'),
  sitTall: (on) => ipcRenderer.send('pet:sit-tall', !!on),
  watchPreset: (mode) => ipcRenderer.send('pet:watch-preset', mode),
  uiState: (st) => ipcRenderer.send('pet:ui-state', st),
  recent: () => ipcRenderer.invoke('pet:recent'),
  bridgeStatus: () => ipcRenderer.invoke('pet:bridge-status'),
  standaloneGet: () => ipcRenderer.invoke('pet:standalone-get'),
  standaloneSave: (cfg) => ipcRenderer.invoke('pet:standalone-save', cfg),
  onCommand: (fn) => ipcRenderer.on('pet:command', (_e, cmd) => fn(cmd)),
  onFeed: (fn) => ipcRenderer.on('pet:feed', (_e, payload) => fn(payload)),
});
